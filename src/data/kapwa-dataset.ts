/**
 * Kapwa's labelled language dataset: example messages and what each means.
 *
 * Used to measure the intent engine (lib/kapwa-eval, `npm run kapwa:eval`)
 * and to improve it, following the plan's split:
 *  - train: used to write and tune keywords freely;
 *  - validation: checked while tuning, to catch over-fitting to train;
 *  - test: held back. Not used for tuning; run to report accuracy.
 *
 * Written to sound like people: short and long, typos, chat shorthand, no
 * question marks, a little Taglish. `intent` is what Kapwa should answer
 * with; a list means any of those is a right answer (some messages fairly
 * fit two topics). Out-of-scope messages expect `fallback` (an honest "I
 * can't help with that") and safety messages `crisis` or `medical-urgent`.
 *
 * The other fields in the plan's schema (entities, response goal, next
 * question, exercise) are derived per example by `datasetRows` in
 * lib/kapwa-eval, so they can't drift from the engine.
 */

export type Split = 'train' | 'validation' | 'test';

export interface Example {
  text: string;
  /** The right answer, or any of several. */
  intent: string | string[];
  split: Split;
  /** Written in Filipino or Hindi (Devanagari or Hinglish); English when absent. */
  lang?: 'fil' | 'hi';
}

type Intent = string | string[];

/**
 * One intent's examples: four or so to train on, one to validate, and two
 * that were round 1's held-back test.
 *
 * Round 1 (25 Nov 2026) scored 80.9% on those. Its misses were then read to
 * fix the engine, so they are no longer unseen: they count as training data
 * now, and round 2's fresh test set (`heldOut`, below) replaced them.
 */
function set(intent: Intent, train: string[], validation: string[], round1Test: string[]): Example[] {
  return [
    ...train.map((text) => ({ text, intent, split: 'train' as const })),
    ...validation.map((text) => ({ text, intent, split: 'validation' as const })),
    ...round1Test.map((text) => ({ text, intent, split: 'train' as const })),
  ];
}

/** Held-back test examples: written before the engine changes they measure, and never tuned against. */
function heldOut(intent: Intent, ...texts: string[]): Example[] {
  return texts.map((text) => ({ text, intent, split: 'test' as const }));
}

/** Examples in another language: `validation` to tune against, `test` held back. */
function inLanguage(lang: 'fil' | 'hi', split: 'validation' | 'test', intent: Intent, ...texts: string[]): Example[] {
  return texts.map((text) => ({ text, intent, split, lang }));
}

